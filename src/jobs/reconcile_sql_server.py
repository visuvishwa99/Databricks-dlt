"""Compare every serving field with the exact snapshot recorded for this run."""

import argparse
import json

from common import PROGRESS_COLUMNS, jdbc_options, validate_run_id
from pyspark.sql import SparkSession


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", required=True)
    parser.add_argument("--schema", required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--secret-scope", default="sis")
    args = parser.parse_args()
    run_id = validate_run_id(args.run_id)
    spark = SparkSession.builder.getOrCreate()
    spark.conf.set("spark.sql.session.timeZone", "UTC")
    options = jdbc_options(spark, args.secret_scope)

    def read(query):
        return spark.read.format("jdbc").options(**options).option("query", query).load()

    audit = read(
        "SELECT TOP (1) run_id, attempt_id, staged_rows FROM dbo.student_progress_write_audit_v2 "
        "ORDER BY snapshot_at DESC"
    ).first()
    if audit is None or audit.run_id != run_id:
        raise RuntimeError("Requested run is not the latest published snapshot; inspect audit history")
    # IDs are validated; attempt_id is generated by UUID and validated again here.
    attempt_id = validate_run_id(audit.attempt_id)
    snapshot = read(
        f"SELECT DISTINCT {', '.join(PROGRESS_COLUMNS)} FROM stg.student_progress_v2 "
        f"WHERE run_id = '{run_id}' AND attempt_id = '{attempt_id}'"
    ).select(*PROGRESS_COLUMNS)
    serving = read(f"SELECT {', '.join(PROGRESS_COLUMNS)} FROM dbo.student_progress").select(*PROGRESS_COLUMNS)
    if snapshot.count() != audit.staged_rows:
        raise RuntimeError("Published staging snapshot missing or changed; retain staging for verification")
    if snapshot.exceptAll(serving).limit(1).count() or serving.exceptAll(snapshot).limit(1).count():
        raise RuntimeError("SQL Server serving data differs from the published snapshot")
    print(json.dumps({"event": "serving_reconciled", "run_id": run_id, "rows": audit.staged_rows}))


if __name__ == "__main__":
    main()
